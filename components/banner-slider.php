<script>
    (function() {
        const track = document.getElementById('hero-slider-track');
        const dots = document.querySelectorAll('.hero-dot');
        const total = 3;
        let activeIdx = 0;
        let timer = null;

        function goToSlide(idx) {
            activeIdx = (idx + total) % total;
            if (track) {
                track.style.transform = `translateX(-${activeIdx * 100}%)`;
            }
            dots.forEach((dot, i) => {
                if (i === activeIdx) {
                    dot.classList.remove('w-2', 'bg-white/70');
                    dot.classList.add('w-7', 'bg-white');
                } else {
                    dot.classList.remove('w-7', 'bg-white');
                    dot.classList.add('w-2', 'bg-white/70');
                }
            });
        }

        function startTimer() {
            timer = setInterval(() => {
                goToSlide(activeIdx + 1);
            }, 5500);
        }

        function resetTimer() {
            clearInterval(timer);
            startTimer();
        }

        dots.forEach(dot => {
            dot.addEventListener('click', () => {
                const idx = parseInt(dot.getAttribute('data-slide') || '0', 10);
                goToSlide(idx);
                resetTimer();
            });
        });

        startTimer();
    })();
</script>
