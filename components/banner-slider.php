<script>
    (function() {
        const track = document.getElementById('hero-slider-track');
        const dots = document.querySelectorAll('.hero-dot');
        const total = 3;
        let activeIdx = 0;
        let timer = null;

        function goToSlide(idx) {
            activeIdx = (idx + total) % total;
            if (track) {
                track.style.transform = `translateX(-${activeIdx * 100}%)`;
            }
            dots.forEach((dot, i) => {
                if (i === activeIdx) {
                    dot.classList.remove('w-2', 'bg-white/70');
                    dot.classList.add('w-7', 'bg-white');
                } else {
                    dot.classList.remove('w-7', 'bg-white');
                    dot.classList.add('w-2', 'bg-white/70');
                }
            });
        }

        function startTimer() {
            timer = setInterval(() => {
                goToSlide(activeIdx + 1);
            }, 5500);
        }

        function resetTimer() {
            clearInterval(timer);
            startTimer();
        }

        // Mobile Touch Swipe Handling
        let touchStartX = 0;
        let touchEndX = 0;
        track?.addEventListener('touchstart', function(e) {
            touchStartX = e.touches[0].clientX;
        }, { passive: true });

        track?.addEventListener('touchend', function(e) {
            touchEndX = e.changedTouches[0].clientX;
            const diffX = touchStartX - touchEndX;
            if (Math.abs(diffX) > 45) {
                if (diffX > 0) {
                    goToSlide(activeIdx + 1); // Swipe left -> Next
                } else {
                    goToSlide(activeIdx - 1); // Swipe right -> Previous
                }
                resetTimer();
            }
        }, { passive: true });

        dots.forEach(dot => {
            dot.addEventListener('click', () => {
                const idx = parseInt(dot.getAttribute('data-slide') || '0', 10);
                goToSlide(idx);
                resetTimer();
            });
        });

        startTimer();
    })();
</script>
